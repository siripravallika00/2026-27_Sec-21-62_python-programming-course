#assignment operators exercises
#augmented assignment operators
x=5
print("x =",x)
x+=3 # equivalent to x=x+3
print("x += 3 => x =",x)
x-=2 # equivalent to x=x-2
print("x -= 2 => x =",x)
x*=4 # equivalent to x=x*4
print("x *= 4 => x =",x)
x//=3 # equivalent to x=x//3
print("x //= 3 => x =",x)
x%=2 # equivalent to x=x%2
print("x %= 2 => x =",x)
x**=2 # equivalent to x=x**2
print("x **= 2 => x =",x)
