# python logical operators
#and(false)
a=2
result= a > 5 and  a<2 # logical and operator  
print("Result of ",a,"> 5 and",a,"<2 is",result)

#or(true)
a=6
result= a >5 or  a<2 # logical or operator
print("Result of ",a,"> 5 or",a,"<2 is",result)

#not(true)
a=7 
result= not(a >5 and  a<2) # logical not operator
print("Result of not(",a,"> 5 and",a,"<2) is",result)






